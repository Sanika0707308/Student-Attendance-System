window.getLang = function () {
    try {
        const stored = localStorage.getItem(LANG_KEY);
        return SUPPORTED_LANGS.includes(stored) ? stored : "en";
    } catch (e) {
        return "en";   // private mode / storage disabled
    }
};

/**
 * Look up one string. Falls back through English to the key itself, so a key
 * that has not been translated yet shows readable English rather than blank
 * space or "undefined".
 */
window.t = function (key, fallback) {
    const lang = window.getLang();
    const table = TRANSLATIONS[lang] || TRANSLATIONS.en;
    if (Object.prototype.hasOwnProperty.call(table, key)) return table[key];
    if (Object.prototype.hasOwnProperty.call(TRANSLATIONS.en, key)) return TRANSLATIONS.en[key];
    return fallback !== undefined ? fallback : key;
};

/** Translate one of the engine's English status values for display. */
window.tStatus = function (status) {
    const key = "status." + String(status || "").replace(/\s+/g, "");
    const translated = window.t(key, null);
    return translated === null ? status : translated;
};

/**
 * Translate and interpolate: tf("students.importedN", {n: 12}).
 *
 * str.replace over a loop rather than a regex on the whole string, for the same
 * reason the Python side avoids str.format — a stray brace in a translation
 * should render as a brace, not throw.
 */
window.tf = function (key, vars, fallback) {
    let out = window.t(key, fallback);
    Object.keys(vars || {}).forEach(name => {
        out = out.split("{" + name + "}").join(String(vars[name]));
    });
    return out;
};

/**
 * Apply every data-i18n* attribute under `root`.
 *
 * The first pass stores the original English in data-i18n-original where an
 * element has no key, which is what lets the language be switched repeatedly
 * without a reload.
 */
window.applyTranslations = function (root = document) {
    root.querySelectorAll("[data-i18n]").forEach(el => {
        el.textContent = window.t(el.dataset.i18n);
    });
    root.querySelectorAll("[data-i18n-html]").forEach(el => {
        // Only ever fed strings from the table above, never user input.
        el.innerHTML = window.t(el.dataset.i18nHtml);
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        el.setAttribute("placeholder", window.t(el.dataset.i18nPlaceholder));
    });
    root.querySelectorAll("[data-i18n-title]").forEach(el => {
        el.setAttribute("title", window.t(el.dataset.i18nTitle));
    });
    root.querySelectorAll("[data-i18n-aria]").forEach(el => {
        el.setAttribute("aria-label", window.t(el.dataset.i18nAria));
    });

    document.documentElement.setAttribute("lang", window.getLang());
};

/**
 * Switch language and reload.
 *
 * A reload rather than a live re-render: most pages build their tables in
 * JavaScript from data they fetched, and re-translating those in place would
 * mean every page keeping a second copy of its render logic. A local reload of
 * a local page is instant, and it guarantees nothing is left in the old
 * language.
 */
window.setLang = function (lang) {
    const next = SUPPORTED_LANGS.includes(lang) ? lang : "en";
    try {
        localStorage.setItem(LANG_KEY, next);
    } catch (e) { /* Falls back to English on the next page view. */ }

    // Mirror the choice into settings so a fresh profile on the same machine —
    // or the next install — opens in the language the office actually uses.
    // Fire-and-forget: the UI has already switched locally either way.
    try {
        fetch("/api/settings/language", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ ui_language: next }),
        }).catch(() => { });
    } catch (e) { /* ignore */ }

    window.location.reload();
};

// Set <html lang> before anything renders. Elements are translated by
// applyTranslations() once the DOM is parsed.
document.documentElement.setAttribute("lang", window.getLang());

document.addEventListener("DOMContentLoaded", () => window.applyTranslations());
